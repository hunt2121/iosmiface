def render(g,S,col=(255,255,255)):
    if isinstance(g[0],str): g=grid(g)
    h=len(g); w=len(g[0]); c=CELL*S; gp=GAP*S
    im=Image.new("RGBA",(round(w*c),round(h*c)),(0,0,0,0)); d=ImageDraw.Draw(im)
    for y,r in enumerate(g):
        for x,v in enumerate(r):
            if v: d.rectangle([x*c,y*c,x*c+c-gp-1,y*c+c-gp-1],fill=col)
    return im
