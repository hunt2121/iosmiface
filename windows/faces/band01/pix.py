def grid(rows):
    return [[1 if ch=="1" else 0 for ch in r] for r in rows]
def compose(base,over,ox,oy,outline=True):
    H=max(len(base),oy+len(over)); W=max(len(base[0]),ox+len(over[0]))
    g=[[0]*W for _ in range(H)]
    for y,r in enumerate(base):
        for x,v in enumerate(r): g[y][x]=v
    if outline:
        for y,r in enumerate(over):
            for x,v in enumerate(r):
                if v:
                    for dy in (-1,0,1):
                        for dx in (-1,0,1):
                            yy,xx=oy+y+dy,ox+x+dx
                            if 0<=yy<H and 0<=xx<W and not (0<=y+dy<len(over) and 0<=x+dx<len(over[0]) and over[y+dy][x+dx]): g[yy][xx]=0
    for y,r in enumerate(over):
        for x,v in enumerate(r):
            if v: g[oy+y][ox+x]=1
    return g
